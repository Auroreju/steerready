"""Convert the Lindström synthetic data pack (.xlsx) into js/data.js.

Usage (from the project folder):
    python3 scripts/build_data.py data/Lindstrom_SinceAI_Customer_Value_Synthetic_Data_Pack.xlsx

The app reads window.LVR_DATA from js/data.js so it can run straight from the
file system (double-click index.html) without a web server. Tables are stored
column-wise ({"cols": [...], "rows": [[...], ...]}) to keep the file small.
To plug in real data later, produce the same tables from Lindström's systems
and re-run this script, or replace js/data.js with an API call.
"""
import json
import sys
from pathlib import Path

import datetime

import openpyxl
import pandas as pd

SHEETS = {
    "Customers": None,
    "Sites": None,
    "Products": None,
    "Laundries": None,
    "Industry_Priorities": None,
    "Baselines": None,
    "Assumptions": None,
    "Data_Quality": None,
    "Service_Activity": ["month", "customer_id", "site_id", "laundry_id", "product_id",
                         "active_wearers", "allocated_pieces", "active_assets_scanned",
                         "washed_pieces", "washing_pct", "customer_washed_kg", "service_requests"],
    "Repairs": ["month", "customer_id", "site_id", "product_id", "repair_type", "repair_count",
                "repair_quotient_pct", "estimated_replacements_postponed",
                "estimated_avoided_product_kgco2e"],
    "Service_Cycles": ["asset_id", "customer_id", "site_id", "product_id", "pickup_timestamp",
                       "cycle_hours", "performance_flag"],
    "Customer_Impacts": ["month", "customer_id", "site_id", "laundry_id", "product_id",
                         "customer_washed_kg", "allocated_water_l", "allocated_energy_kwh",
                         "allocated_process_kgco2e", "allocated_delivery_kgco2e",
                         "allocated_textile_waste_kg"],
    "Laundry_Resources": None,
    "Waste_Circularity": None,
}


def clean(value):
    if isinstance(value, pd.Timestamp):
        return value.strftime("%Y-%m-%d")
    if isinstance(value, float):
        if value != value:  # NaN
            return None
        return round(value, 4)
    if hasattr(value, "item"):
        return value.item()
    return value


def main(path):
    book = pd.read_excel(path, sheet_name=None)
    out = {}
    for sheet, cols in SHEETS.items():
        df = book[sheet]
        if cols:
            df = df[cols]
        out[sheet] = {
            "cols": list(df.columns),
            "rows": [[clean(v) for v in row] for row in df.itertuples(index=False)],
        }
    props = openpyxl.load_workbook(path, read_only=True).properties
    months = sorted(book["Service_Activity"]["month"].astype(str))
    out["meta"] = {
        "sourceFile": Path(path).name,
        "sourceLastUpdated": (props.modified or props.created).strftime("%Y-%m-%d") if (props.modified or props.created) else None,
        "generatedAt": datetime.datetime.now().strftime("%Y-%m-%d"),
        "periodStart": months[0],
        "periodEnd": months[-1],
    }
    target = Path(__file__).resolve().parent.parent / "js" / "data.js"
    text = "/* Generated by scripts/build_data.py from the synthetic data pack. Do not edit by hand. */\n"
    text += "window.LVR_DATA = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
    target.write_text(text, encoding="utf-8")
    print(f"Wrote {target} ({target.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else
         "data/Lindstrom_SinceAI_Customer_Value_Synthetic_Data_Pack.xlsx")
