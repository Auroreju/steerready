"""Convert every data sheet of the Lindström data pack (all columns) into js/data_full.js.

This is the data the AI assistant queries. The dashboard's own figures still come from
js/data.js (built by build_data.py), so the two can be refreshed independently.

Usage (from the project folder):
    python3 scripts/build_full_data.py data/Lindstrom_SinceAI_Customer_Value_Synthetic_Data_Pack.xlsx
"""
import datetime
import json
import sys
from pathlib import Path

import pandas as pd

DATA_SHEETS = [
    "Customers", "Sites", "Products", "Laundries", "Industry_Priorities", "Baselines",
    "Assumptions", "Data_Quality", "Service_Activity", "Repairs", "Service_Cycles",
    "Customer_Impacts", "Laundry_Resources", "Waste_Circularity",
]


def clean(value):
    if isinstance(value, (pd.Timestamp, datetime.datetime)):
        return value.strftime("%Y-%m-%d %H:%M")
    if isinstance(value, float):
        if value != value:
            return None
        return round(value, 4)
    if hasattr(value, "item"):
        return value.item()
    return value


def main(path):
    book = pd.read_excel(path, sheet_name=None)
    out = {"tables": {}}
    for sheet in DATA_SHEETS:
        df = book[sheet]
        out["tables"][sheet] = {
            "cols": [str(c) for c in df.columns],
            "rows": [[clean(v) for v in row] for row in df.itertuples(index=False)],
        }
    dd = book["Data_Dictionary"]
    out["dictionary"] = [
        {k: clean(v) for k, v in row.items()} for row in dd.to_dict("records")
    ]
    readme = book["README"]
    out["readme"] = "\n".join(
        " ".join(str(v) for v in row if v == v and v is not None)
        for row in readme.itertuples(index=False)
    ).strip()
    target = Path(__file__).resolve().parent.parent / "js" / "data_full.js"
    text = "/* Generated by scripts/build_full_data.py: every data sheet, every column. Do not edit by hand. */\n"
    text += "window.LVR_FULL = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
    target.write_text(text, encoding="utf-8")
    print(f"Wrote {target} ({target.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else
         "data/Lindstrom_SinceAI_Customer_Value_Synthetic_Data_Pack.xlsx")
